-- ===============================UParActionCondition===============================
--
-- 作用：
--     给动作候选增加一个外部否决条件。
--     核心的几何、按键、速度、启用状态等条件仍然是最终底线。
--     这个钩子只能否决动作，不能强行开启动作。
--
-- 运行端：
--     服务端
--
-- 签名：
--     hook.Add('UParActionCondition', '唯一名称', function(ply, context)
--         -- return false 表示否决当前动作
--         -- 不返回表示不否决
--     end)
--
-- 参数：
--     ply        Player
--     context    table
--
-- context.action：
--     string
--     当前动作名称，可能为：
--         low_climb
--         high_climb
--         vault
--         double_vault
--         vertical_wallrun
--         horizontal_wallrun
--
-- context.kind：
--     string
--     普通跑酷：
--         platform
--         pulse
--     墙跑：
--         vertical
--         horizontal
--
-- context.data：
--     table
--     检测器返回的类型化数据：
--         UPar.Platform
--         UPar.Pulse
--         UPar.VerticalWallrun
--         UPar.HorizontalWallrun
--
-- context.cmd：
--     CUserCmd 或 nil
--     通过控制台命令触发时可能为 nil。
--
-- 返回值：
--     return false    否决当前动作候选
--     不返回            不否决
--
--     不要返回 true。
--     不要修改 context，context 只用于读取。
--     判定只看钩子的返回值，不读取 context 中的字段。
--
-- 调用时机：
--     当前动作候选已经通过核心基础条件，并且轮到它参与优先级判定时调用。
--     如果被否决，核心会继续尝试更低优先级的动作。
--
--     需要读取当前旧 move 时，由开发者自行读取 ply.upar_motion。
--


-- ===============================UParActionNodes===============================
--
-- 作用：
--     在动作已经通过全部核心条件后，覆盖该动作的整套运动节点。
--     这是动作级覆盖，不是逐节点修改，也不是动作权限检查。
--
-- 运行端：
--     服务端
--
-- 签名：
--     hook.Add('UParActionNodes', '唯一名称', function(ply, context, nodes)
--         return nodes
--     end)
--
-- 参数：
--     ply        Player
--     context    table，只读上下文
--     nodes      UPar.Node 数组，默认节点
--
-- context.action：
--     string
--     当前动作名称，可能为：
--         low_climb
--         high_climb
--         vault
--         double_vault
--         vertical_wallrun
--         horizontal_wallrun
--
-- context.kind：
--     string
--     普通跑酷：
--         platform
--         pulse
--     墙跑：
--         vertical
--         horizontal
--
-- context.data：
--     table，检测器返回的类型化数据
--
-- context.cmd：
--     CUserCmd 或 nil
--
-- 返回值：
--     return nodes    使用返回的整套节点
--     return nil      保留核心默认节点
--
--     不要 return false，取消动作属于 UParActionCondition。
--     不要修改 context。
--
-- 注意：
--     需要读取当前旧 move 时，由开发者自行读取 ply.upar_motion。
--     空闲状态可能为 nil，墙跑中断转普通跑酷时通常是旧墙跑 move。
--
--     多个 UParActionNodes 同时注册时，第一个返回非 nil 的钩子会终止后续调用，
--     只有返回 table 才会替换 nodes。不要让多个插件同时接管同一动作节点。
--
-- 警告：
--     UParActionNodes 是危险钩子，它会直接替换整套运动节点。
--     返回 nodes 后，节点、flag、payload、运动生命周期和特效生命周期
--     全部由开发者自己负责。
--     核心不会校验、修复、补默认值或清理自定义 flag。
--     开发者可以保留核心 flag，也可以完全使用自己的 flag。
--


-- ===============================UParMoveFlag===============================
--
-- 作用：
--     监听运动节点 flag。
--     这是节点特效、音效、动画和统计信息的公开事件。
--     它不是动作权限检查。
--
-- 运行端：
--     服务端和客户端
--
-- 签名：
--     hook.Add('UParMoveFlag', '唯一名称', function(ply, flag, payload)
--     end)
--
-- 参数：
--     ply        Player
--     flag       string，节点 flag 或手动动作 flag
--     payload    table 或 nil，随 flag 发送的附加数据
--
-- 注意：
--     本钩子由核心统一分发，开发者只需要 hook.Add 监听。
--     payload 是只读数据，可能为 nil。
--     不要修改 payload，也不要调用 hook.Run('UParMoveFlag') 自己发送事件。
--     节点事件的数据来自 node.payload，手动事件的数据由 action 提供。
--     服务端和客户端收到相同的 flag 与 payload。
--     node、move、timeline 不会作为 payload 传递，监听者不应依赖这些内部对象。
--
-- 示例：
--     horizontal_wallrun payload = {
--         along = Vector,
--         side = 'left' 或 'right',
--     }
--
-- 起始 flag payload：
--     low_climb_start / high_climb_start:
--         landing
--         normal
--
--     vault_start:
--         landing
--         vaultLanding
--         normal
--
--     double_vault_state1:
--         landing
--         normal
--
--     double_vault_state2:
--         vaultLanding
--         normal
--
--     vertical_wallrun_start:
--         normal
--         along
--         contactPos
--
--     horizontal_wallrun_start:
--         normal
--         along
--         side
--         contactPos
--
-- 过程、结束、中断和跳跃 flag 当前不带 payload。
--
-- 当前内置的节点 flag：
--     low_climb_start
--     high_climb_start
--     vault_start
--     double_vault_state1
--     double_vault_state2
--     vertical_wallrun_start
--     vertical_wallrun_step
--     horizontal_wallrun_start
--     horizontal_wallrun_step
--     low_climb_end
--     high_climb_end
--     vault_end
--     double_vault_end
--     vertical_wallrun_end
--     horizontal_wallrun_end
--
-- 当前内置的手动 flag：
--     wallrun_interrupt
--     vertical_wallrun_jump
--     horizontal_wallrun_jump
